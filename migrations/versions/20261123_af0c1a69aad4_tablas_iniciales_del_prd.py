# Defensa en la base: aunque el código tenga un error, PostgreSQL no permite
# - insertar una recarga en un estado distinto de PENDING;
# - transiciones fuera de PENDING → SUBMITTED → SUCCESS | FAILED | UNKNOWN,
#   UNKNOWN → SUCCESS | FAILED, y PENDING → FAILED (rechazo antes del envío);
# - modificar una recarga en estado final (SUCCESS, FAILED);
# - cambiar identidad, monto o destino de una recarga, ni el SKU/operador una vez enviada.
TOPUP_GUARD_SQL = """
CREATE FUNCTION topups_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'PENDING' THEN
            RAISE EXCEPTION 'topups: una recarga nueva debe empezar en PENDING (recibido %)',
                NEW.status USING ERRCODE = 'check_violation';
        END IF;
        RETURN NEW;
    END IF;

    IF OLD.status IN ('SUCCESS', 'FAILED') THEN
        RAISE EXCEPTION 'topups: la recarga % está en estado final % y no se modifica',
            OLD.id, OLD.status USING ERRCODE = 'check_violation';
    END IF;

    IF NEW.id IS DISTINCT FROM OLD.id
       OR NEW.product_id IS DISTINCT FROM OLD.product_id
       OR NEW.env IS DISTINCT FROM OLD.env
       OR NEW.reward_id IS DISTINCT FROM OLD.reward_id
       OR NEW.external_ref IS DISTINCT FROM OLD.external_ref
       OR NEW.phone IS DISTINCT FROM OLD.phone
       OR NEW.amount IS DISTINCT FROM OLD.amount
       OR NEW.currency IS DISTINCT FROM OLD.currency
       OR NEW.correlation_id IS DISTINCT FROM OLD.correlation_id
       OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'topups: campos inmutables modificados en %', OLD.id
            USING ERRCODE = 'check_violation';
    END IF;

    IF OLD.status <> 'PENDING' AND (
           NEW.sku_id IS DISTINCT FROM OLD.sku_id
           OR NEW.operator_id IS DISTINCT FROM OLD.operator_id
           OR NEW.submitted_at IS DISTINCT FROM OLD.submitted_at) THEN
        RAISE EXCEPTION 'topups: % ya fue enviada; SKU, operador y fecha de envío no cambian',
            OLD.id USING ERRCODE = 'check_violation';
    END IF;

    IF NEW.status IS DISTINCT FROM OLD.status AND NOT (
           (OLD.status = 'PENDING'   AND NEW.status IN ('SUBMITTED', 'FAILED'))
        OR (OLD.status = 'SUBMITTED' AND NEW.status IN ('SUCCESS', 'FAILED', 'UNKNOWN'))
        OR (OLD.status = 'UNKNOWN'   AND NEW.status IN ('SUCCESS', 'FAILED'))) THEN
        RAISE EXCEPTION 'topups: transición inválida % → % en %', OLD.status, NEW.status, OLD.id
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER topups_guard
    BEFORE INSERT OR UPDATE ON topups
    FOR EACH ROW EXECUTE FUNCTION topups_guard();
"""


